// OMNIVERSE server actions.
//
// Two responsibilities:
//  1. The keyed document store (getDoc / putDoc / deleteDoc / exportAll /
//     importAll) that persists every environment's state.
//  2. omniChat — the single Gemini gateway for OMNI, the unified assistant.
//     The user's Gemini API key is held only in their browser and arrives
//     per-request; it is used once, in the x-goog-api-key header, and never
//     stored server-side. With no key (or on any API failure) omniChat
//     returns a clearly labeled DEMO MODE reply composed from the real
//     context summary the client built out of live simulation state —
//     it never pretends to be a live Gemini answer.
//
// AI never writes simulation state directly. When Gemini returns a fenced
// JSON block tagged `omni-proposal`, the server parses and returns it as a
// structured proposal; the client validates it against the current state
// and only applies it after the user confirms.

import { defineAction, z, type ActionsModule } from "@hatch/space-sdk";
import { eq } from "drizzle-orm";
import * as schema from "./schema";

const ENVIRONMENTS = [
  "hub",
  "nexus",
  "orbit",
  "sonora",
  "empire",
  "casefile",
  "aether",
  "chronicles",
  "sentinel",
] as const;

const proposalSchema = z
  .object({
    action: z.string().min(1).max(60),
    label: z.string().min(1).max(160),
    params: z.record(z.string(), z.union([z.string(), z.number(), z.boolean()])).default({}),
  })
  .nullable();

const omniResponse = z.object({
  reply: z.string(),
  demo: z.boolean(),
  model: z.string(),
  proposal: proposalSchema,
});

type OmniResponse = z.infer<typeof omniResponse>;

const ROLE_BY_ENV: Record<string, string> = {
  hub: "OMNI, the unified intelligence of OMNIVERSE, a connected digital universe of simulations and creative tools",
  nexus: "OMNI in the role of civilization advisor inside NEXUS, a civilization simulator",
  orbit: "OMNI in the role of ship computer and scientific advisor inside ORBIT, a space exploration simulator",
  sonora: "OMNI in the role of creative music producer inside SONORA, a music production studio",
  empire: "OMNI in the role of business consultant inside EMPIRE, a business and entrepreneurship simulator",
  casefile: "OMNI in the role of investigation assistant inside CASEFILE, a fictional detective universe. Every case is fictional. Never reveal a case solution unless the user explicitly asks for a spoiler",
  aether: "OMNI in the role of operating-system assistant inside AETHER, a browser-based OS. AETHER files are virtual files inside OMNIVERSE, not files on the user's real computer",
  chronicles: "OMNI in the role of guide and narrator inside CHRONICLES, a fantasy adventure universe. Stay in the fictional world; keep mechanics to the app",
  sentinel: "OMNI in the role of defensive cybersecurity tutor and analyst inside SENTINEL. All SENTINEL data is simulated and labeled as such. Help only with defensive, educational security topics; never help with unauthorized access or real-world attacks",
};

function demoReply(env: string, mode: string, message: string, context: string): string {
  const role = ROLE_BY_ENV[env] ?? ROLE_BY_ENV.hub;
  const lines: string[] = [
    `**DEMO MODE** — no Gemini key is connected, so this reply is composed locally from your live ${env.toUpperCase()} state rather than generated by Gemini. Add your free Gemini key in Settings → OMNI / Gemini to switch to live answers.`,
    "",
    `Acting as ${role}, here is what I can see right now:`,
    context ? context : "No environment context was shared for this message.",
  ];
  const m = message.toLowerCase();
  if (m.includes("help") || m.includes("what can you do")) {
    lines.push(
      "",
      "Ask me about anything on screen: I read the current environment's real numbers before answering. Try \"what should I focus on?\", \"explain this\", or \"suggest a next step\".",
    );
  } else if (m.includes("suggest") || m.includes("next step") || m.includes("focus") || m.includes("advice")) {
    lines.push(
      "",
      "My suggestion: work from the figures above — fix the tightest constraint first (the lowest resource, the oldest open item, or the highest severity), then re-check here. In live mode I can also draft a concrete, validated action proposal for you to approve.",
    );
  } else if (m.includes("explain") || m.includes("why") || m.includes("what is")) {
    lines.push(
      "",
      "In short: everything I explain is grounded in the state summary above — the app, not the AI, owns every calculation, so those numbers are exact. In live mode I'll expand this into a full explanation with examples.",
    );
  } else {
    lines.push(
      "",
      `On "${message}": based on the state above, the honest demo-mode answer is that the data is in front of you and consistent — connect Gemini for a full reasoning pass, creative drafting, or character roleplay on exactly this context.`,
    );
  }
  if (mode && mode !== "default") lines.push("", `Mode: ${mode}.`);
  return lines.join("\n");
}

function extractProposal(text: string): { reply: string; proposal: z.infer<typeof proposalSchema> } {
  const match = text.match(/```omni-proposal\s*\n([\s\S]*?)\n```/);
  if (!match || !match[1]) return { reply: text, proposal: null };
  let proposal: z.infer<typeof proposalSchema> = null;
  try {
    const parsed = proposalSchema.safeParse(JSON.parse(match[1]));
    if (parsed.success) proposal = parsed.data;
  } catch {
    proposal = null;
  }
  return { reply: text.replace(match[0], "").trim(), proposal };
}

export const Actions = {
  getDoc: defineAction({
    description: "Reads one OMNIVERSE state document by key; returns null data when it does not exist yet.",
    request: z.object({ key: z.string().min(1).max(80) }),
    response: z.object({ key: z.string(), data: z.string().nullable() }),
    async handler(ctx, args) {
      const db = ctx.db<typeof schema>();
      const rows = await db.select().from(schema.docs).where(eq(schema.docs.key, args.key)).limit(1);
      return { key: args.key, data: rows[0]?.data ?? null };
    },
  }),

  putDoc: defineAction({
    description: "Creates or replaces one OMNIVERSE state document (JSON string) under its key.",
    request: z.object({ key: z.string().min(1).max(80), data: z.string().max(2_000_000) }),
    response: z.object({ ok: z.literal(true) }),
    async handler(ctx, args): Promise<{ ok: true }> {
      const db = ctx.db<typeof schema>();
      await db
        .insert(schema.docs)
        .values({ key: args.key, data: args.data, updatedAt: new Date() })
        .onConflictDoUpdate({
          target: schema.docs.key,
          set: { data: args.data, updatedAt: new Date() },
        });
      ctx.invalidateQueries();
      return { ok: true };
    },
  }),

  deleteDoc: defineAction({
    description: "Deletes one OMNIVERSE state document by key (used by per-environment resets).",
    request: z.object({ key: z.string().min(1).max(80) }),
    response: z.object({ ok: z.literal(true) }),
    async handler(ctx, args): Promise<{ ok: true }> {
      const db = ctx.db<typeof schema>();
      await db.delete(schema.docs).where(eq(schema.docs.key, args.key));
      ctx.invalidateQueries();
      return { ok: true };
    },
  }),

  exportAll: defineAction({
    description: "Returns every OMNIVERSE state document for backup/export.",
    request: z.object({}),
    response: z.object({ docs: z.array(z.object({ key: z.string(), data: z.string() })) }),
    async handler(ctx) {
      const db = ctx.db<typeof schema>();
      const rows = await db.select().from(schema.docs);
      return { docs: rows.map((r) => ({ key: r.key, data: r.data })) };
    },
  }),

  importAll: defineAction({
    description: "Replaces OMNIVERSE state with an exported backup (array of key/JSON documents).",
    request: z.object({
      docs: z.array(z.object({ key: z.string().min(1).max(80), data: z.string().max(2_000_000) })).max(40),
    }),
    response: z.object({ ok: z.literal(true), count: z.number() }),
    async handler(ctx, args): Promise<{ ok: true; count: number }> {
      const db = ctx.db<typeof schema>();
      for (const doc of args.docs) {
        // Validate JSON so a corrupt backup cannot poison the store.
        JSON.parse(doc.data);
        await db
          .insert(schema.docs)
          .values({ key: doc.key, data: doc.data, updatedAt: new Date() })
          .onConflictDoUpdate({
            target: schema.docs.key,
            set: { data: doc.data, updatedAt: new Date() },
          });
      }
      ctx.invalidateQueries();
      return { ok: true, count: args.docs.length };
    },
  }),

  omniChat: defineAction({
    description:
      "Sends one message to OMNI, the unified Gemini assistant, with a bounded summary of the current environment's real state. Uses the per-request API key when supplied; otherwise returns a labeled demo-mode reply.",
    request: z.object({
      environment: z.enum(ENVIRONMENTS),
      mode: z.string().max(60).default("default"),
      message: z.string().min(1).max(6000),
      context: z.string().max(6000).default(""),
      history: z
        .array(z.object({ role: z.enum(["user", "model"]), text: z.string().max(4000) }))
        .max(12)
        .default([]),
      apiKey: z.string().max(200).optional(),
      model: z.string().max(80).default("gemini-3.1-flash-lite"),
    }),
    response: omniResponse,
    async handler(ctx, args): Promise<OmniResponse> {
      void ctx;
      const model = args.model.trim() || "gemini-3.1-flash-lite";
      const key = args.apiKey?.trim();
      if (!key) {
        return { reply: demoReply(args.environment, args.mode, args.message, args.context), demo: true, model, proposal: null };
      }
      const system = [
        `You are ${ROLE_BY_ENV[args.environment]}.`,
        "You receive a bounded summary of the user's current state in this environment. Use only that context; never invent numbers that contradict it. The application owns all mechanics and calculations — you advise, explain, create and roleplay; you never claim to have changed state.",
        "If (and only if) a concrete in-app action would clearly help, you may append ONE fenced block tagged ```omni-proposal containing JSON {\"action\": string, \"label\": string, \"params\": {string: string|number|boolean}}. The app validates proposals and asks the user before applying anything.",
        args.mode && args.mode !== "default" ? `Active mode: ${args.mode}.` : "",
        "Keep answers focused and practical. Markdown is supported.",
      ]
        .filter(Boolean)
        .join("\n");
      const contents = [
        ...args.history.map((h) => ({ role: h.role, parts: [{ text: h.text }] })),
        {
          role: "user" as const,
          parts: [
            {
              text: args.context
                ? `[Current ${args.environment.toUpperCase()} state]\n${args.context}\n\n[User message]\n${args.message}`
                : args.message,
            },
          ],
        },
      ];
      try {
        const res = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`,
          {
            method: "POST",
            headers: { "Content-Type": "application/json", "x-goog-api-key": key },
            body: JSON.stringify({
              systemInstruction: { parts: [{ text: system }] },
              contents,
              generationConfig: { temperature: 0.7, maxOutputTokens: 1400 },
            }),
            signal: AbortSignal.timeout(45000),
          },
        );
        if (!res.ok) {
          const detail = await res.text().catch(() => "");
          return {
            reply: `**Gemini connection problem (HTTP ${res.status}).** ${detail.slice(0, 300)}\n\nFalling back for this reply — ${demoReply(args.environment, args.mode, args.message, args.context)}`,
            demo: true,
            model,
            proposal: null,
          };
        }
        const json = (await res.json()) as {
          candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
        };
        const text =
          json.candidates?.[0]?.content?.parts?.map((p) => p.text ?? "").join("") ?? "";
        if (!text) {
          return { reply: demoReply(args.environment, args.mode, args.message, args.context), demo: true, model, proposal: null };
        }
        const { reply, proposal } = extractProposal(text);
        return { reply, demo: false, model, proposal };
      } catch (err) {
        return {
          reply: `**Gemini is unreachable right now** (${err instanceof Error ? err.message : "network error"}).\n\nFalling back for this reply — ${demoReply(args.environment, args.mode, args.message, args.context)}`,
          demo: true,
          model,
          proposal: null,
        };
      }
    },
  }),
} satisfies ActionsModule;
